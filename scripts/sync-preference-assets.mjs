import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parseArgs } from 'node:util';
import { ROOT, main, safePath, logStatus } from './lib/runtime.mjs';
import { PREFERENCE_COOKIE_NAMES } from '../apps/web/src/cookies/core.js';

const sourcePath = 'apps/web/src/cookies/core.js';

/** One browser-only source, emitted as a classic script for both independently served themes. */
export function preferenceAsset(source) {
  source = source.replaceAll('\r\n', '\n');
  if (/^import\s/m.test(source)) throw new Error('Preference cookie core must be self-contained');
  const names = [...source.matchAll(/^export (?:function|const) (\w+)/gm)].map(match => match[1]);
  if (!names.length) throw new Error('Preference cookie core has no exports');
  const digest = createHash('sha256').update(source).digest('hex').slice(0, 16);
  return `// Generated by scripts/sync-preference-assets.mjs from ${sourcePath}; source ${digest}. Do not edit.\n` +
    `(() => {\n"use strict";\n${source.replace(/^export /gm, '')}\n` +
    `globalThis.FormiqPreferenceCookies = Object.freeze({ ${names.join(', ')} });\n})();\n`;
}

export async function synchronizePreferenceAssets(root = ROOT, { check = false } = {}) {
  const source = await readFile(await safePath(root, sourcePath), 'utf8');
  const asset = preferenceAsset(source);
  const version = createHash('sha256').update(asset).digest('hex').slice(0, 12);
  for (const theme of ['login', 'account']) {
    const directory = `infra/local/keycloak/themes/FORMIQ/${theme}`;
    const relative = `${directory}/resources/js/preference-cookies.js`;
    const parent = await safePath(root, `${directory}/resources/js`);
    if (!parent) throw new Error(`Missing theme resources: ${theme}`);
    const target = await safePath(root, relative) ?? `${parent}/preference-cookies.js`;
    let current;
    try { current = await readFile(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current?.replaceAll('\r\n', '\n') !== asset) {
      if (check) throw new Error(`Stale preference asset: ${relative}. Run pnpm preferences:sync`);
      await writeFile(target, asset);
    }
    const propertiesPath = await safePath(root, `${directory}/theme.properties`);
    const properties = await readFile(propertiesPath, 'utf8');
    const expected = properties
      .replace(/(FORMIQ_THEME_COOKIE_NAME:)[^}]+/g, `$1${PREFERENCE_COOKIE_NAMES.theme}`)
      .replace(/preference-cookies\.js\?v=[^\s]+/g, `preference-cookies.js?v=${version}`);
    if (expected !== properties) {
      if (check) throw new Error(`Stale default cookie name in ${directory}/theme.properties`);
      await writeFile(propertiesPath, expected);
    }
  }
}

main(import.meta.url, async () => {
  const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
  await synchronizePreferenceAssets(ROOT, values);
  logStatus(`[ok] Preference cookie assets ${values.check ? 'verified' : 'synchronized'}.`);
});
